//! Browser extension handshake, state reporting, and validation (05 §1–§2).

use std::fmt;

use serde::{Deserialize, Serialize};
use snafu::Snafu;

use crate::{ProtoRange, Uuid};

/// Maximum UTF-16 code units permitted in a reported browser tab title (05 §1.2).
pub const BROWSER_TITLE_MAX_UTF16_UNITS: usize = 4_096;

/// Sentinel domain reported for browser internal pages (05 §1.2).
pub const INTERNAL_BROWSER_DOMAIN: &str = "(internal)";

/// Sentinel domain reported for local `file://` pages (05 §1.2).
pub const LOCAL_FILE_BROWSER_DOMAIN: &str = "(local-file)";

/// Maximum length of a DNS hostname without a trailing root dot (RFC 1035).
const MAX_DOMAIN_LEN: usize = 253;

/// Maximum length of a single DNS hostname label (RFC 1035).
const MAX_DOMAIN_LABEL_LEN: usize = 63;

/// Punycode ACE prefix for internationalized domain labels.
const PUNYCODE_PREFIX: &str = "xn--";

/// Supported browser families reported by the extension (05 §1.1).
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Hash,
    Serialize,
    Deserialize,
    strum::IntoStaticStr,
    strum::VariantArray,
)]
#[serde(rename_all = "snake_case")]
#[strum(serialize_all = "snake_case")]
pub enum BrowserKind {
    /// Google Chrome.
    Chrome,
    /// Microsoft Edge.
    Edge,
    /// Mozilla Firefox.
    Firefox,
}

/// Browser-specific handshake payload carried in core `hello` (05 §2.2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BrowserHello {
    /// Browser family reporting this profile.
    pub browser: BrowserKind,
    /// Stable profile identity generated by the extension in `storage.local`.
    pub profile_instance_id: Uuid,
}

/// First request body sent by the browser extension to `quartz-host.exe` (05 §1.2).
///
/// `browser.hello` is a host-level operation translated by `quartz-host.exe` into core `hello`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BrowserHostHello {
    /// Stable profile identity generated by the extension in `storage.local`.
    pub profile_instance_id: Uuid,
    /// Browser family reporting this profile.
    pub browser: BrowserKind,
    /// Protocol versions supported by the extension.
    pub proto: ProtoRange,
}

/// Whether a browser window is currently focused (05 §1.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(from = "bool", into = "bool")]
pub enum BrowserFocus {
    /// A window belonging to this browser profile has focus.
    Focused,
    /// No window belonging to this browser profile has focus.
    Unfocused,
}

impl From<bool> for BrowserFocus {
    fn from(value: bool) -> Self {
        if value {
            Self::Focused
        } else {
            Self::Unfocused
        }
    }
}

impl From<BrowserFocus> for bool {
    fn from(value: BrowserFocus) -> Self {
        value == BrowserFocus::Focused
    }
}

/// Browser window display state reported by the extension (05 §1.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BrowserWindowState {
    /// Standard restored window.
    Normal,
    /// Maximized window.
    Maximized,
    /// Minimized window.
    Minimized,
    /// Fullscreen window.
    Fullscreen,
}

/// Active browser window metadata (05 §1.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BrowserWindow {
    /// Browser-assigned window identifier (not a Win32 HWND).
    pub id: i64,
    /// Window display state.
    pub state: BrowserWindowState,
}

/// Status of a reported browser tab title (05 §1.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BrowserTitleStatus {
    /// Full title was reported within the UTF-16 cap.
    Ok,
    /// The tab title is empty.
    Empty,
    /// The extension truncated the title to the 4,096 UTF-16 unit cap.
    Truncated,
}

/// Whether the reported tab is producing audio (05 §1.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(from = "bool", into = "bool")]
pub enum BrowserAudible {
    /// The tab is currently audible.
    Audible,
    /// The tab is silent.
    Silent,
}

impl From<bool> for BrowserAudible {
    fn from(value: bool) -> Self {
        if value { Self::Audible } else { Self::Silent }
    }
}

impl From<BrowserAudible> for bool {
    fn from(value: BrowserAudible) -> Self {
        value == BrowserAudible::Audible
    }
}

/// Validation failure for a `browser.state` payload; never retains titles or domains.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Snafu)]
pub enum ValidateBrowserStateError {
    /// Tab title exceeds the 4,096 UTF-16 code-unit limit.
    #[snafu(display(
        "browser tab title length {utf16_units} exceeds {BROWSER_TITLE_MAX_UTF16_UNITS} UTF-16 code units"
    ))]
    TitleTooLong {
        /// Observed UTF-16 code-unit count.
        utf16_units: usize,
    },
    /// Domain is neither a valid lowercase ASCII/punycode host nor a known sentinel.
    #[snafu(display("browser tab domain is invalid"))]
    InvalidDomain,
}

/// Validates that a browser tab title fits within [`BROWSER_TITLE_MAX_UTF16_UNITS`].
///
/// # Errors
/// Returns [`ValidateBrowserStateError::TitleTooLong`] when the UTF-16 length exceeds the limit.
pub fn validate_browser_title(title: &str) -> Result<(), ValidateBrowserStateError> {
    let utf16_units = title.encode_utf16().count();
    if utf16_units > BROWSER_TITLE_MAX_UTF16_UNITS {
        return Err(ValidateBrowserStateError::TitleTooLong { utf16_units });
    }
    Ok(())
}

/// Validates a reported browser domain without retaining the input on failure.
///
/// Accepts lowercase ASCII/punycode hostnames (without scheme, port, path, or trailing dot)
/// and the fixed sentinels `(internal)` and `(local-file)`.
///
/// # Errors
/// Returns [`ValidateBrowserStateError::InvalidDomain`] for malformed, uppercase, or non-ASCII domains.
pub fn validate_browser_domain(domain: &str) -> Result<(), ValidateBrowserStateError> {
    if domain == INTERNAL_BROWSER_DOMAIN || domain == LOCAL_FILE_BROWSER_DOMAIN {
        return Ok(());
    }
    if domain.is_empty() || domain.len() > MAX_DOMAIN_LEN {
        return Err(ValidateBrowserStateError::InvalidDomain);
    }
    for label in domain.split('.') {
        if label.is_empty() || label.len() > MAX_DOMAIN_LABEL_LEN {
            return Err(ValidateBrowserStateError::InvalidDomain);
        }
        if label.starts_with('-') || label.ends_with('-') {
            return Err(ValidateBrowserStateError::InvalidDomain);
        }
        if !label
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
        {
            return Err(ValidateBrowserStateError::InvalidDomain);
        }
        if let Some(punycode) = label.strip_prefix(PUNYCODE_PREFIX)
            && punycode.is_empty()
        {
            return Err(ValidateBrowserStateError::InvalidDomain);
        }
    }
    Ok(())
}

/// Active browser tab metadata (05 §1.2).
///
/// `Debug` intentionally omits `domain` and `title` so logs can never leak browsing content.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(try_from = "BrowserTabWire")]
pub struct BrowserTab {
    /// Browser-assigned tab identifier.
    pub id: i64,
    /// Lowercase ASCII/punycode host, `(internal)`, `(local-file)`, or absent.
    pub domain: Option<String>,
    /// Tab title capped at 4,096 UTF-16 code units.
    pub title: String,
    /// Whether the title is complete, empty, or truncated.
    pub title_status: BrowserTitleStatus,
    /// Whether the tab is currently playing audio.
    pub audible: BrowserAudible,
}

impl BrowserTab {
    /// Validates title UTF-16 length and domain format.
    ///
    /// # Errors
    /// Returns a typed validation error without retaining private content.
    pub fn validate(&self) -> Result<(), ValidateBrowserStateError> {
        validate_browser_title(&self.title)?;
        if let Some(domain) = &self.domain {
            validate_browser_domain(domain)?;
        }
        Ok(())
    }
}

impl fmt::Debug for BrowserTab {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("BrowserTab")
            .field("id", &self.id)
            .field("has_domain", &self.domain.is_some())
            .field("title_utf16_len", &self.title.encode_utf16().count())
            .field("title_status", &self.title_status)
            .field("audible", &self.audible)
            .finish()
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct BrowserTabWire {
    id: i64,
    domain: Option<String>,
    title: String,
    title_status: BrowserTitleStatus,
    audible: BrowserAudible,
}

impl TryFrom<BrowserTabWire> for BrowserTab {
    type Error = ValidateBrowserStateError;

    fn try_from(value: BrowserTabWire) -> Result<Self, Self::Error> {
        let tab = Self {
            id: value.id,
            domain: value.domain,
            title: value.title,
            title_status: value.title_status,
            audible: value.audible,
        };
        tab.validate()?;
        Ok(tab)
    }
}

/// Request body for `browser.state` (05 §1.2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BrowserStateRequest {
    /// Whether the browser profile currently has window focus.
    pub focused: BrowserFocus,
    /// Active browser window metadata, absent when no window is open.
    pub window: Option<BrowserWindow>,
    /// Active tab metadata, absent when unfocused or no tab is active.
    pub tab: Option<BrowserTab>,
}

impl BrowserStateRequest {
    /// Validates the enclosed tab payload when present.
    ///
    /// # Errors
    /// Returns a typed validation error without retaining private content.
    pub fn validate(&self) -> Result<(), ValidateBrowserStateError> {
        if let Some(tab) = &self.tab {
            tab.validate()?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{AcceptedBody, CoreRequest, Hello, Op};

    fn snapshot<T: serde::de::DeserializeOwned + Serialize>(value: &serde_json::Value) {
        let decoded: T = serde_json::from_value(value.clone()).expect("typed browser wire value");
        assert_eq!(serde_json::to_value(decoded).expect("browser JSON"), *value);
    }

    #[test]
    fn browser_wire_snapshots_cover_hello_state_and_stream() {
        let wire: serde_json::Value =
            serde_json::from_str(include_str!("../tests/fixtures/browser.json"))
                .expect("browser wire snapshots");
        snapshot::<Hello>(&wire["core_hello"]);
        snapshot::<BrowserHostHello>(&wire["host_hello"]);
        snapshot::<BrowserStateRequest>(&wire["state_focused"]);
        snapshot::<BrowserStateRequest>(&wire["state_unfocused"]);
        snapshot::<BrowserStateRequest>(&wire["state_minimized"]);
        snapshot::<BrowserStateRequest>(&wire["state_internal"]);
        snapshot::<BrowserStateRequest>(&wire["state_local_file"]);
        snapshot::<AcceptedBody>(&wire["accepted"]);
        snapshot::<crate::BrowserStream>(&wire["stream"]);
        assert_eq!(BrowserStateRequest::OP, Op::BrowserState);
    }

    #[test]
    fn browser_kind_wire_names_match_static_strings() {
        use strum::VariantArray;
        for kind in BrowserKind::VARIANTS {
            let name: &'static str = (*kind).into();
            assert_eq!(serde_json::to_value(kind).expect("browser kind"), name);
        }
    }

    #[test]
    fn browser_state_enforces_4096_utf16_title_boundary_with_cjk_and_emoji() {
        let exact_ascii = "a".repeat(BROWSER_TITLE_MAX_UTF16_UNITS);
        let over_ascii = "a".repeat(BROWSER_TITLE_MAX_UTF16_UNITS + 1);
        let exact_cjk = "中".repeat(BROWSER_TITLE_MAX_UTF16_UNITS);
        let over_cjk = "中".repeat(BROWSER_TITLE_MAX_UTF16_UNITS + 1);
        // Each U+1F600 emoji occupies two UTF-16 code units (a surrogate pair).
        let exact_emoji = "😀".repeat(BROWSER_TITLE_MAX_UTF16_UNITS / 2);
        let over_emoji_by_one = format!("{exact_emoji}a");
        let over_emoji_by_two = "😀".repeat(BROWSER_TITLE_MAX_UTF16_UNITS / 2 + 1);

        for valid in [&exact_ascii, &exact_cjk, &exact_emoji, ""] {
            let wire = serde_json::json!({
                "focused": true,
                "window": { "id": 1, "state": "normal" },
                "tab": {
                    "id": 2,
                    "domain": "github.com",
                    "title": valid,
                    "title_status": "truncated",
                    "audible": false
                }
            });
            let parsed: BrowserStateRequest =
                serde_json::from_value(wire).expect("title within 4096 UTF-16 units");
            assert!(parsed.validate().is_ok());
        }

        for (invalid, expected_units) in [
            (&over_ascii, BROWSER_TITLE_MAX_UTF16_UNITS + 1),
            (&over_cjk, BROWSER_TITLE_MAX_UTF16_UNITS + 1),
            (&over_emoji_by_one, BROWSER_TITLE_MAX_UTF16_UNITS + 1),
            (&over_emoji_by_two, BROWSER_TITLE_MAX_UTF16_UNITS + 2),
        ] {
            assert_eq!(
                validate_browser_title(invalid),
                Err(ValidateBrowserStateError::TitleTooLong {
                    utf16_units: expected_units,
                })
            );
            let wire = serde_json::json!({
                "focused": true,
                "window": { "id": 1, "state": "normal" },
                "tab": {
                    "id": 2,
                    "domain": "github.com",
                    "title": invalid,
                    "title_status": "truncated",
                    "audible": false
                }
            });
            assert!(serde_json::from_value::<BrowserStateRequest>(wire).is_err());
        }
    }

    #[test]
    fn browser_domain_validation_accepts_lowercase_ascii_punycode_and_sentinels() {
        for valid in [
            "github.com",
            "sub.domain.example.co.uk",
            "localhost",
            "127.0.0.1",
            "xn--fsqu00a.xn--0zwm56d",
            "xn--mnchen-3ya.de",
            "ab--cd.github.io",
            "(internal)",
            "(local-file)",
        ] {
            assert_eq!(validate_browser_domain(valid), Ok(()), "valid: {valid}");
        }

        let long_label = format!("{}.com", "a".repeat(MAX_DOMAIN_LABEL_LEN + 1));
        let long_domain = std::array::from_fn::<_, 4, _>(|_| "a".repeat(63)).join(".");
        for invalid in [
            "",
            "GitHub.com",
            "XN--FSQU00A.com",
            "例子.测试",
            "münchen.de",
            "https://github.com",
            "github.com:443",
            "github.com/4o3F/quartz",
            "github .com",
            ".github.com",
            "github.com.",
            "a..b.com",
            "-a.com",
            "a-.com",
            "xn--",
            "xn--.com",
            "(other)",
            "(internal) ",
            "a_b.com",
            &long_label,
            &long_domain,
        ] {
            assert_eq!(
                validate_browser_domain(invalid),
                Err(ValidateBrowserStateError::InvalidDomain),
                "invalid: {invalid}"
            );
            let wire = serde_json::json!({
                "focused": true,
                "window": null,
                "tab": {
                    "id": 1,
                    "domain": invalid,
                    "title": "ok",
                    "title_status": "ok",
                    "audible": false
                }
            });
            assert!(serde_json::from_value::<BrowserStateRequest>(wire).is_err());
        }
    }

    #[test]
    fn browser_state_rejects_unknown_fields_and_redacts_debug_output() {
        assert!(
            serde_json::from_value::<BrowserStateRequest>(serde_json::json!({
                "focused": false,
                "window": null,
                "tab": null,
                "extra": true
            }))
            .is_err()
        );
        assert!(
            serde_json::from_value::<BrowserStateRequest>(serde_json::json!({
                "focused": true,
                "window": { "id": 1, "state": "normal", "extra": true },
                "tab": null
            }))
            .is_err()
        );
        assert!(
            serde_json::from_value::<BrowserStateRequest>(serde_json::json!({
                "focused": true,
                "window": null,
                "tab": {
                    "id": 1,
                    "domain": "secret-host.example",
                    "title": "Top Secret Tab Title",
                    "title_status": "ok",
                    "audible": true,
                    "extra": true
                }
            }))
            .is_err()
        );

        let state: BrowserStateRequest = serde_json::from_value(serde_json::json!({
            "focused": true,
            "window": { "id": 7, "state": "maximized" },
            "tab": {
                "id": 91,
                "domain": "secret-host.example",
                "title": "Top Secret Tab Title",
                "title_status": "ok",
                "audible": true
            }
        }))
        .expect("valid browser state");
        let debug = format!("{state:?}");
        assert!(!debug.contains("secret-host.example"));
        assert!(!debug.contains("Top Secret Tab Title"));
    }
}
